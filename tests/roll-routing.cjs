const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '..', 'scripts', 'player-actions.js'), 'utf8');
const hooks = {};
const captures = [];
const actor = {id: 'mage1', uuid: 'Actor.mage1', name: 'Test Mage', type:'PC', isOwner: true,
  system:{settings:{splat:'mage'}}, items:[
    {name:'Arete',type:'Advantage',system:{id:'arete',permanent:3}},
    {name:'Quintessence',type:'Advantage',system:{id:'quintessence',temporary:0}},
    {name:'Life',type:'Sphere',system:{id:'life',value:3}},
    {name:'Mind',type:'Sphere',system:{id:'mind',value:2}},
  ]};
const moduleInstance = {api:null};
const ctx = {
  Hooks:{once:(k,v)=>hooks[k]=v,on:(k,v)=>hooks[k]=v},
  game:{system:{id:'worldofdarkness'},modules:{get:()=>moduleInstance},user:{isGM:false,character:actor},keybindings:{register:()=>{}}},
  ui:{notifications:{warn:()=>{},error:(e)=>{throw Error(e)}}},
  canvas:{tokens:{controlled:[]}},
  foundry:{utils:{escapeHTML:x=>String(x)}},
  CONST:{KEYBINDING_PRECEDENCE:{NORMAL:1}},
  HTMLElement:class {},document:{querySelector:()=>null},console,
};
// Mock the WoD20 roller without doing a second roll. Its rendered chat template
// accepts origin magic, power, general and does not accept origin arete.
const nativeMock = {
  DiceRollContainer:class {constructor(a){this.actor=a;}},
  DiceRoller:async roll=>{
    captures.push({origin:roll.origin, title:roll.action, pool:roll.numDices, difficulty:roll.difficulty, extras:roll.extraInfo});
    if (!['magic','power','general','soak','item','attack','damage','initiative','send'].includes(roll.origin)) {
      throw Error('WoD20 roll-template.hbs cannot render origin '+roll.origin);
    }
    return 2;
  }
};
vm.runInNewContext(source + '\n;globalThis.__runDice=runDice; globalThis.__performMageCast=performMageCast; globalThis.__activatePower=activatePower; globalThis.__injectDice=(value)=>wodDice=value;', ctx);
ctx.__injectDice(nativeMock);
(async()=>{
  await ctx.__performMageCast(actor, null, {'sphere.Life':'3','sphere.Mind':'0',reality:'coincidental',quint:'0',modifier:'0',effect:'Heal wounds'});
  assert.equal(captures.length,1, 'Just one native roll');
  assert.equal(captures[0].origin,'magic','The recognized native spell-card type is magic');
  assert.equal(captures[0].pool,3);
  assert.equal(captures[0].difficulty,6);
  assert.match(captures[0].title,/Arete.*Heal wounds/);
  assert.ok(captures[0].extras.some(x=>x.includes('Spheres: Life 3')));
  await ctx.__runDice(actor,{title:'Summon light',pool:3,difficulty:7});
  assert.equal(captures[1].origin,'general','Generic roller defaults to recognized type');
  const power={id:'power1',name:'Presence',type:'Power',parent:actor};
  actor.items.push(power);
  // Native item method supplied: expect delegated activation, not a second roll.
  let activated = false;
  power.use = async()=>{activated=true;};
  await ctx.__activatePower(actor,power);
  assert.equal(activated,true);
  assert.equal(captures.length,2,'No duplicate generated by native activation');
  console.log('PASS: guided magick -> WoD20 magic chat-card type, recognized default type, no extra roll.');
})().catch(e=>{console.error(e);process.exitCode=1;});
